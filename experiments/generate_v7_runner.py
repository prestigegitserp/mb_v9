"""Generate the V7 resource wrapper from the unchanged, pinned V8 runner.

Only storage and lookup changes are made. Helpers resolve through pub so V7
factories and progress instrumentation remain effective.
"""
import argparse
import ast
import builtins
import hashlib
from pathlib import Path
import symtable


def generate(root):
    original=(root/'vendor_v8/mbmf_q1_infrastructure_v8.py').read_text()
    module=ast.parse(original)
    function=next(n for n in module.body if isinstance(n,ast.FunctionDef) and n.name=='run_publication_study_v8')
    source=ast.get_source_segment(original,function)
    symbols=symtable.symtable(source,'native','exec').get_children()[0]
    globals_={s.get_name() for s in symbols.get_symbols() if s.is_global() and s.is_referenced() and not hasattr(builtins,s.get_name())}
    class Resolve(ast.NodeTransformer):
        def visit_Name(self,node):
            if isinstance(node.ctx,ast.Load) and node.id in globals_:
                return ast.copy_location(ast.Attribute(value=ast.Name(id='pub',ctx=ast.Load()),attr=node.id,ctx=node.ctx),node)
            return node
    function=Resolve().visit(function);function.name='_run_study'
    function.args.args.insert(0,ast.arg(arg='pub'))
    for argument in function.args.args:argument.annotation=None
    function.returns=None
    changes=[]
    def call(name,*args):return ast.Call(func=ast.Name(id=name,ctx=ast.Load()),args=list(args),keywords=[])
    def name(value):return ast.Name(id=value,ctx=ast.Load())
    class Storage(ast.NodeTransformer):
        def visit_AnnAssign(self,node):
            if isinstance(node.target,ast.Name) and node.target.id=='split_frames':
                node.value=ast.Constant(None);changes.append('frame_declaration')
            elif isinstance(node.target,ast.Name) and node.target.id=='data_cache':
                node.value=call('OneEntryCache');changes.append('tensor_cache')
            return self.generic_visit(node)
        def visit_Assign(self,node):
            if isinstance(node.value,ast.Call) and isinstance(node.value.func,ast.Attribute) and node.value.func.attr=='load_publication_dataset':
                node.value=call('shared_load',name('pub'),name('cfg'),name('out'))
                extra=ast.Assign(targets=[ast.Name(id='split_frames',ctx=ast.Store())],value=call('SplitFrames',name('raw'),name('cfg'),name('pub'),name('spec')))
                changes.append('dataset_and_roles');return [node,extra]
            if isinstance(node.targets[0],ast.Subscript) and isinstance(node.targets[0].value,ast.Name) and node.targets[0].value.id=='split_frames':
                node.value=name('split');changes.append('role_insertion')
            return self.generic_visit(node)
        def visit_Expr(self,node):
            if isinstance(node.value,ast.Call) and isinstance(node.value.func,ast.Attribute):
                func=node.value.func
                if isinstance(func.value,ast.Name) and func.value.id=='split' and func.attr=='to_csv':
                    key=ast.BinOp(left=ast.Constant('split_'),op=ast.Add(),right=call('str',name('split_seed')))
                    node.value=call('shared_csv',name('split'),node.value.args[0],name('cfg'),key);changes.append('shared_split_csv')
                elif func.attr=='export_split_for_external':
                    node.value=call('shared_export',name('pub'),name('data'),node.value.args[1],name('cfg'),name('split_seed'),name('out'))
                    changes.append('shared_external_csv')
            return self.generic_visit(node)
    function=Storage().visit(function)
    assert sorted(changes)==sorted(['frame_declaration','tensor_cache','dataset_and_roles','role_insertion','shared_split_csv','shared_external_csv']),changes
    ast.fix_missing_locations(function)
    header='''"""V7 bounded-storage runner; scientific selection is inherited from pinned V8.

Generated by experiments/generate_v7_runner.py. All calls through pub retain
the active scoped model factories, validation rules and reporting hooks.
"""
from __future__ import annotations
from .split_cache import SplitFrames,OneEntryCache,shared_load,shared_csv,shared_export
'''
    header+='NATIVE_FUNCTION_SHA256 = '+repr(hashlib.sha256(source.encode()).hexdigest())+'\n\n'
    wrapper='''

def run_study(pub,cfg,*args,**kwargs):
    try:
        return _run_study(pub,cfg,*args,**kwargs)
    finally:
        store=getattr(cfg,"_v7_split_frames",None)
        if store is not None:store.close()
'''
    return header+ast.unparse(function)+'\n'+wrapper


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    parser.add_argument('--output',type=Path)
    args=parser.parse_args(argv)
    (args.output or args.root/'v7/runner.py').write_text(generate(args.root),encoding='utf8')


if __name__=='__main__':main()
