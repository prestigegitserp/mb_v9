"""V7 bounded-storage runner; scientific selection is inherited from pinned V8.

Generated by experiments/generate_v7_runner.py. All calls through pub retain
the active scoped model factories, validation rules and reporting hooks.
"""
from __future__ import annotations
from .split_cache import SplitFrames,OneEntryCache,shared_load,shared_csv,shared_export
NATIVE_FUNCTION_SHA256 = 'ddfbada9daa5e0f23f6d08a0df31e1cb95d830f32e0fb7daf71f2f2b7c93742d'

def _run_study(pub, cfg, device=None):
    """Publication runner with strict validation-only selection and locked test.

    Train and validation metrics are computed for every candidate. Test metrics are
    first computed only after one configuration has been selected by mean validation
    RMSE within each dataset/split/model block. Selected checkpoints are persisted.
    """
    if not cfg.strict_locked_test:
        raise ValueError('V8 publication runner requires strict_locked_test=True')
    pub.scientific_core_immutability_test_v8()
    device = device or pub.core.get_device()
    out = pub.Path(cfg.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    cand_dir = out / '_candidate_checkpoints'
    cand_dir.mkdir(parents=True, exist_ok=True)
    selected_dir = out / 'selected_models'
    selected_dir.mkdir(parents=True, exist_ok=True)
    rows: pub.List[pub.Dict[str, pub.Any]] = []
    histories: pub.Dict[str, pub.Any] = {}
    split_frames: pub.Dict[int, pub.pd.DataFrame] = None
    raw, spec = shared_load(pub, cfg, out)
    split_frames = SplitFrames(raw, cfg, pub, spec)
    manifest = {'dataset': cfg.data.dataset, 'documented_range': [spec.rating_min, spec.rating_max], 'rating_step': spec.rating_step, 'n_interactions': int(len(raw)), 'n_users': int(raw.userId.nunique()), 'n_items': int(raw.movieId.nunique()), 'frozen_v7_core_sha256': pub.FROZEN_V7_CORE_SHA256, 'infrastructure_revision': pub.V8_REVISION}
    with open(out / 'dataset_manifest.json', 'w', encoding='utf-8') as f:
        pub.json.dump(manifest, f, indent=2)
    split_seeds = tuple(cfg.core_config.split_seeds)
    model_seeds = tuple(cfg.core_config.model_seeds)
    latent_dims = tuple(cfg.core_config.latent_dims)
    first_k = int(latent_dims[0])
    for split_seed in split_seeds:
        dc = pub.copy.deepcopy(cfg.data)
        dc.split_seed = int(split_seed)
        split = pub.make_core_split(raw, spec, dc)
        if any(((split.split == sp).sum() == 0 for sp in ('train', 'val', 'test'))):
            raise ValueError(f'split {split_seed} has empty train/validation/test partition; cannot report publication metrics')
        split_frames[int(split_seed)] = split
        shared_csv(split, out / f'split_assignments_{split_seed}.csv', cfg, 'split_' + str(split_seed))
        data, backend = pub.build_publication_matrix_data_v8(split, spec, dc, device)
        shared_export(pub, data, out / 'external_splits' / f'{cfg.data.dataset}__split{split_seed}.csv', cfg, split_seed, out)
        for k in latent_dims:
            for method in cfg.methods:
                if cfg.respect_dataset_method_matrix and (not pub.method_supported_on_dataset_v8(method, cfg.data.dataset)):
                    continue
                if method in ('AutoRec', 'AEMC-NE') and int(k) != first_k:
                    continue
                modes = cfg.core_config.paper.init_modes if method in ('MBMF-F', 'MBMF-C', 'MBMF-N') else ('NA',)
                for init_mode in modes:
                    for model_seed in model_seeds:
                        model, mcfg = pub.instantiate_model_v8(method, data, cfg, int(k), int(model_seed), device, None if init_mode == 'NA' else init_mode)
                        with pub.PeakMemoryMonitor(device) as mm:
                            t0 = pub.time.perf_counter()
                            info = pub.train_model_v8(method, model, data, mcfg, cfg)
                            train_wall = pub.time.perf_counter() - t0
                        train_met = pub.evaluate_publication_model(model, data, 'train', metric_cfg=cfg.metrics)
                        if cfg.save_predictions:
                            val_met, val_pred = pub.evaluate_publication_model(model, data, 'val', metric_cfg=cfg.metrics, return_predictions=True)
                        else:
                            val_met = pub.evaluate_publication_model(model, data, 'val', metric_cfg=cfg.metrics)
                            val_pred = None
                        diag_val = pub._model_diagnostics_v8(model, data, 'val')
                        cp = cand_dir / f'{cfg.data.dataset}__{method}__split{split_seed}__seed{model_seed}__K{k}__{init_mode}.pt'
                        pub.save_model_checkpoint_v8(cp, model, config=mcfg, data=data, train_info=info, extra={'dataset': cfg.data.dataset, 'init_mode': init_mode, 'method': method, 'backend': backend})
                        row = {'dataset': cfg.data.dataset, 'method': method, 'backend': backend, 'split_seed': int(split_seed), 'model_seed': int(model_seed), 'K': pub.np.nan if method in ('AutoRec', 'AEMC-NE') else int(k), 'init_mode': init_mode, 'train_wall_sec': train_wall, 'parameter_count': pub.core.parameter_count(model), 'checkpoint_path': str(cp), 'config_key': pub._candidate_config_key_v8(method, mcfg, init_mode), 'best_epoch': info.get('best_epoch', info.get('final_epoch', pub.np.nan)), 'timestamp_status': getattr(data, 'train_timestamp_status', 'unknown'), **mm.metrics(), **{f'train_{a}': b for a, b in train_met.items()}, **{f'val_{a}': b for a, b in val_met.items()}, **{f'valdiag_{a}': b for a, b in diag_val.items()}}
                        if cfg.save_predictions and val_pred is not None:
                            vpp = pub._prediction_archive_path_v8(out, cfg.data.dataset, method, int(split_seed), int(model_seed), pub.np.nan if method in ('AutoRec', 'AEMC-NE') else int(k), init_mode, 'val')
                            pub.save_prediction_archive_v8(vpp, data, val_pred, 'val')
                            row['val_prediction_file'] = str(vpp)
                        rows.append(row)
                        histories[f'{method}|split={split_seed}|seed={model_seed}|K={k}|init={init_mode}'] = info.get('history', [])
                        pub.pd.DataFrame(rows).drop(columns=['checkpoint_path'], errors='ignore').to_csv(out / 'candidate_validation_runs.csv', index=False)
                        del model
                        pub.gc.collect()
                        if device.type == 'cuda':
                            pub.torch.cuda.empty_cache()
    candidates = pub.pd.DataFrame(rows)
    if cfg.save_predictions and (not candidates.empty):
        kstab = pub.prediction_variation_across_k_v8(candidates, split='val')
        if not kstab.empty:
            kstab.to_csv(out / 'prediction_stability_across_K_validation.csv', index=False)
            if cfg.auto_generate_plots:
                pub.plot_k_stability_v8(kstab, out / 'figures')
    forbidden = [c for c in candidates.columns if c.startswith('test_')]
    if forbidden:
        raise AssertionError(f'test leakage into candidate table: {forbidden}')
    selected = pub._selected_config_rows_v8(candidates)
    selected.drop(columns=['checkpoint_path'], errors='ignore').to_csv(out / 'selected_by_validation_candidates.csv', index=False)
    if cfg.validation_only:
        with open(out / 'training_histories.json', 'w', encoding='utf-8') as f:
            pub.json.dump(pub._jsonable(histories), f, indent=2)
        with open(out / 'config.json', 'w', encoding='utf-8') as f:
            pub.json.dump(pub._jsonable(pub.asdict(cfg)), f, indent=2)
        if not cfg.save_candidate_checkpoints:
            pub.shutil.rmtree(cand_dir, ignore_errors=True)
        return (candidates.drop(columns=['checkpoint_path'], errors='ignore'), pub.pd.DataFrame())
    locked_rows: pub.List[pub.Dict[str, pub.Any]] = []
    data_cache: pub.Dict[int, pub.MatrixLike] = OneEntryCache()
    for _, row in selected.iterrows():
        ss = int(row.split_seed)
        if ss not in data_cache:
            dc = pub.copy.deepcopy(cfg.data)
            dc.split_seed = ss
            data_cache[ss], _ = pub.build_publication_matrix_data_v8(split_frames[ss], spec, dc, device)
        data = data_cache[ss]
        model, ck = pub.load_model_checkpoint_v8(row.checkpoint_path, data, device)
        outrow = row.drop(labels=['checkpoint_path']).to_dict()
        for sp in ('train', 'val', 'test'):
            t0 = pub.time.perf_counter()
            met, pred = pub.evaluate_publication_model(model, data, sp, metric_cfg=cfg.metrics, return_predictions=True)
            infer = pub.time.perf_counter() - t0
            outrow.update({f'{sp}_{a}': b for a, b in met.items()})
            outrow[f'{sp}_inference_sec'] = infer
            outrow.update({f'{sp}diag_{a}': b for a, b in pub._model_diagnostics_v8(model, data, sp).items()})
            if cfg.save_predictions:
                pp = pub._prediction_archive_path_v8(out, cfg.data.dataset, str(row.method), ss, int(row.model_seed), row.K, str(row.init_mode), sp)
                pub.save_prediction_archive_v8(pp, data, pred, sp)
                outrow[f'{sp}_prediction_file'] = str(pp)
        if cfg.save_selected_checkpoints:
            selp = selected_dir / f"{cfg.data.dataset}__{row.method}__split{ss}__seed{int(row.model_seed)}__K{('NA' if pub.pd.isna(row.K) else int(row.K))}__{row.init_mode}.pt"
            pub.shutil.copy2(row.checkpoint_path, selp)
            outrow['selected_checkpoint'] = str(selp)
        locked_rows.append(outrow)
        del model
        pub.gc.collect()
        if device.type == 'cuda':
            pub.torch.cuda.empty_cache()
    locked = pub.pd.DataFrame(locked_rows)
    locked.to_csv(out / 'locked_test_runs.csv', index=False)
    summary = pub.summarise_publication_runs(locked)
    summary.to_csv(out / 'locked_test_summary.csv', index=False)
    numeric = [c for c in locked.select_dtypes(include=pub.np.number).columns if c not in ('model_seed',)]
    split_means = locked.groupby(['dataset', 'method', 'split_seed'], as_index=False)[numeric].mean(numeric_only=True)
    split_means.to_csv(out / 'locked_test_split_means.csv', index=False)
    if cfg.save_predictions:
        st = pub.attach_prediction_stability(locked.rename(columns={'test_prediction_file': 'test_prediction_file'}))
        if not st.empty:
            st.to_csv(out / 'prediction_stability_across_seeds.csv', index=False)
    with open(out / 'training_histories.json', 'w', encoding='utf-8') as f:
        pub.json.dump(pub._jsonable(histories), f, indent=2)
    with open(out / 'config.json', 'w', encoding='utf-8') as f:
        pub.json.dump(pub._jsonable(pub.asdict(cfg)), f, indent=2)
    env = {'python': pub.platform.python_version(), 'torch': pub.torch.__version__, 'numpy': pub.np.__version__, 'pandas': pub.pd.__version__, 'device': str(device), 'v8': pub.V8_REVISION, 'frozen_v7_core_sha256': pub.FROZEN_V7_CORE_SHA256}
    with open(out / 'environment.json', 'w', encoding='utf-8') as f:
        pub.json.dump(env, f, indent=2)
    if not cfg.save_candidate_checkpoints:
        pub.shutil.rmtree(cand_dir, ignore_errors=True)
    if cfg.auto_run_statistics and (not locked.empty):
        try:
            pub.pairwise_wilcoxon_holm(split_means, metric='test_RMSE', group_cols=('dataset', 'split_seed')).to_csv(out / 'wilcoxon_holm.csv', index=False)
        except Exception as exc:
            pub.warnings.warn(f'Wilcoxon-Holm skipped: {exc}')
        try:
            ranks, stat = pub.friedman_nemenyi_summary(split_means, metric='test_RMSE', block_cols=('dataset', 'split_seed'))
            ranks.to_csv(out / 'friedman_average_ranks.csv', index=False)
            pub.pd.DataFrame([stat]).to_csv(out / 'friedman_nemenyi_stats.csv', index=False)
        except Exception as exc:
            pub.warnings.warn(f'Friedman/Nemenyi skipped: {exc}')
    if cfg.auto_generate_plots and (not locked.empty):
        try:
            from mbmf_q1_visuals_v8 import generate_publication_figures_v8
            generate_publication_figures_v8(locked, out, out / 'training_histories.json')
        except Exception as exc:
            (out / 'figure_generation_error.txt').write_text(repr(exc), encoding='utf-8')
            raise RuntimeError(f'Publication figure generation failed: {exc}') from exc
    return (candidates.drop(columns=['checkpoint_path'], errors='ignore'), locked)


def run_study(pub,cfg,*args,**kwargs):
    try:
        return _run_study(pub,cfg,*args,**kwargs)
    finally:
        store=getattr(cfg,"_v7_split_frames",None)
        if store is not None:store.close()
